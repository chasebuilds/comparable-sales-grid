"""Seeded synthetic housing market with known true values.

Every number here is generated by code. No real people, owners or addresses.
Prices follow a log-linear model plus a hidden location field the estimator never sees,
so the benchmark measures a tool that has to recover the structure from noisy sales.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

ATTRS = ("gla", "beds", "baths", "age", "lot", "condition", "quality")

# name, centre x km, centre y km, base price at 1,800 sf (synthetic dollars)
NEIGHBORHOODS: tuple[tuple[str, float, float, float], ...] = (
    ("Oak Ridge", 2.0, 2.0, 215_000),
    ("Mill Creek", 5.5, 1.5, 175_000),
    ("Hollow Run", 8.5, 3.0, 140_000),
    ("Riverside", 1.5, 6.0, 255_000),
    ("Old Town", 5.0, 5.5, 195_000),
    ("Ridgeview", 9.0, 7.0, 165_000),
    ("Lakeshore", 3.0, 9.5, 290_000),
    ("Pine Flats", 7.0, 9.0, 150_000),
)
NB_WEIGHTS = (0.16, 0.14, 0.10, 0.12, 0.18, 0.10, 0.08, 0.12)

BASE_YEAR, BASE_MONTH = 2023, 11
N_MONTHS = 36  # sales span months 0..35; valuation month is 36
VALUATION_DATE = "2026-11-01"

# True coefficients on ln(price). Used only to generate data and score the estimator.
TRUE = {
    "gla": 0.85,  # elasticity on ln(gla / 1800)
    "beds": 0.015,
    "baths": 0.035,
    "age": -0.0045,
    "lot": 0.10,  # elasticity on ln(lot / 9000)
    "condition": 0.045,
    "quality": 0.065,
}
SALE_NOISE_SD = 0.045


def true_log_index(month: np.ndarray) -> np.ndarray:
    """ln of the market index (month 0 = 0). Trend, season and a late acceleration."""
    m = np.asarray(month, dtype=float)
    out = 0.0045 * m + 0.012 * np.sin(2 * np.pi * m / 12) + 0.03 * np.maximum(0.0, m - 24) / 12
    return np.asarray(out, dtype=float)


def _draw_homes(rng: np.random.Generator, n: int) -> pd.DataFrame:
    nb_idx = rng.choice(len(NEIGHBORHOODS), size=n, p=list(NB_WEIGHTS))
    centres = np.array([(c[1], c[2]) for c in NEIGHBORHOODS])
    xy = centres[nb_idx] + rng.normal(0, 0.6, size=(n, 2))
    gla = np.clip(np.exp(rng.normal(np.log(1750), 0.28, n)), 700, 4800).round(-1)
    beds = np.clip(np.round(2 + (gla - 1200) / 650 + rng.normal(0, 0.6, n)), 1, 6)
    baths = np.clip(np.round((1 + (gla - 900) / 1100 + rng.normal(0, 0.5, n)) * 2) / 2, 1, 4)
    age = np.clip(rng.gamma(2.2, 16, n), 0, 110).round()
    lot = np.clip(np.exp(rng.normal(np.log(9500), 0.55, n)), 3000, 80_000).round(-2)
    condition = rng.choice([1, 2, 3, 4, 5], n, p=[0.04, 0.14, 0.42, 0.28, 0.12])
    quality = rng.choice([1, 2, 3, 4, 5], n, p=[0.04, 0.18, 0.46, 0.24, 0.08])
    return pd.DataFrame(
        {
            "neighborhood": [NEIGHBORHOODS[i][0] for i in nb_idx],
            "x_km": xy[:, 0].round(3),
            "y_km": xy[:, 1].round(3),
            "gla": gla,
            "beds": beds,
            "baths": baths,
            "age": age,
            "lot": lot,
            "condition": condition,
            "quality": quality,
        }
    )


def true_log_value_at_month0(df: pd.DataFrame) -> np.ndarray:
    base = {c[0]: np.log(c[3]) for c in NEIGHBORHOODS}
    nb = df["neighborhood"].map(base).to_numpy(dtype=float)
    x = df["x_km"].to_numpy(dtype=float)
    y = df["y_km"].to_numpy(dtype=float)
    hidden = 0.04 * np.sin(0.9 * x) * np.cos(0.7 * y)  # micro-location the model never sees
    age = df["age"].to_numpy(dtype=float)
    age_eff = TRUE["age"] * np.minimum(age, 30) + 0.5 * TRUE["age"] * np.maximum(age - 30, 0)
    out = (
        nb
        + hidden
        + TRUE["gla"] * np.log(df["gla"].to_numpy(dtype=float) / 1800)
        + TRUE["beds"] * (df["beds"].to_numpy(dtype=float) - 3)
        + TRUE["baths"] * (df["baths"].to_numpy(dtype=float) - 2)
        + age_eff
        + TRUE["lot"] * np.log(df["lot"].to_numpy(dtype=float) / 9000)
        + TRUE["condition"] * (df["condition"].to_numpy(dtype=float) - 3)
        + TRUE["quality"] * (df["quality"].to_numpy(dtype=float) - 3)
    )
    return np.asarray(out, dtype=float)


def month_to_date(month: int, day: int = 1) -> str:
    total = BASE_YEAR * 12 + (BASE_MONTH - 1) + month
    return f"{total // 12:04d}-{total % 12 + 1:02d}-{day:02d}"


@dataclass(frozen=True)
class Market:
    sales: pd.DataFrame
    subjects: pd.DataFrame
    valuation_date: str


def generate_market(n_sales: int = 3000, n_subjects: int = 200, seed: int = 20261122) -> Market:
    rng = np.random.default_rng(seed)
    sales = _draw_homes(rng, n_sales)
    month = rng.integers(0, N_MONTHS, n_sales)
    day = rng.integers(1, 29, n_sales)
    base_ln = true_log_value_at_month0(sales)
    true_at_sale = np.exp(base_ln + true_log_index(month))
    price = true_at_sale * np.exp(rng.normal(0, SALE_NOISE_SD, n_sales))
    sales.insert(0, "sale_id", [f"S{i:05d}" for i in range(n_sales)])
    sales["sale_date"] = [month_to_date(int(m), int(d)) for m, d in zip(month, day, strict=True)]
    sales["sale_price"] = price.round(-2)
    sales["true_value_at_sale"] = true_at_sale.round(-2)
    sales = sales.sort_values("sale_date").reset_index(drop=True)

    subjects = _draw_homes(rng, n_subjects)
    val_ln = true_log_value_at_month0(subjects) + true_log_index(np.array([N_MONTHS]))[0]
    subjects.insert(0, "subject_id", [f"P{i:04d}" for i in range(n_subjects)])
    subjects["true_value"] = np.exp(val_ln).round(-2)
    return Market(sales=sales, subjects=subjects, valuation_date=VALUATION_DATE)
